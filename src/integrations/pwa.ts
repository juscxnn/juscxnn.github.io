import type { AstroIntegration } from "astro";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

async function walk(root: string, dir = root): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true });
  const out: string[] = [];
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(root, full)));
    else out.push(relative(root, full).split(sep).join("/"));
  }
  return out;
}

const CACHEABLE = /\.(html|css|js|png|svg|webmanifest|vcf|ico)$/;

export default function climbPwa(): AstroIntegration {
  return {
    name: "climb-pwa",
    hooks: {
      "astro:build:done": async ({ dir, logger }) => {
        const root = fileURLToPath(dir);
        const files = (await walk(root))
          .filter((f) => CACHEABLE.test(f) && !f.endsWith("sw.js"))
          .sort();

        const entries = [];
        for (const f of files) {
          const buf = await readFile(join(root, f));
          entries.push({
            url: "/" + f,
            rev: createHash("sha256").update(buf).digest("hex").slice(0, 12),
          });
        }

        const cache = "climb-" + createHash("sha256").update(JSON.stringify(entries)).digest("hex").slice(0, 16);

        const sw = `/* generated by src/integrations/pwa.ts */
const CACHE = ${JSON.stringify(cache)};
const ASSETS = ${JSON.stringify(entries)};
const PAGE = "/index.html";

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await Promise.all(ASSETS.map((a) => cache.add(new Request(a.url, { cache: "reload" })).catch(() => {})));
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  if (req.mode === "navigate") {
    event.respondWith((async () => {
      try {
        const res = await fetch(req);
        const cache = await caches.open(CACHE);
        cache.put(req, res.clone());
        return res;
      } catch {
        const hit = await caches.match(req);
        if (hit) return hit;
        const page = url.pathname.endsWith("/") ? url.pathname + "index.html" : url.pathname;
        return (await caches.match(page)) || (await caches.match(PAGE)) || Response.error();
      }
    })());
    return;
  }

  event.respondWith((async () => {
    const hit = await caches.match(req);
    if (hit) return hit;
    const res = await fetch(req);
    if (res.ok && res.type === "basic") {
      const cache = await caches.open(CACHE);
      cache.put(req, res.clone());
    }
    return res;
  })());
});
`;

        await writeFile(join(root, "sw.js"), sw, "utf8");
        logger.info(`sw.js written · ${entries.length} precached · ${cache}`);
      },
    },
  };
}
